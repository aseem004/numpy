import matplotlib.pyplot as plt
 # Data structure: [restaurant_id, 2021, 2022, 2023, 2024]
sales_data = np.array([
    [1, 150000, 180000, 220000, 250000],  # Paradise Biryani
    [2, 120000, 140000, 160000, 190000],  # Beijing Bites
    [3, 200000, 230000, 260000, 300000],  # Pizza Hub
    [4, 180000, 210000, 240000, 270000],  # Burger Point
    [5, 160000, 185000, 205000, 230000]   # Chai Point
])
print("sample data of first 3 restaurants:", sales_data[:3,1:5])
# sales[slice row , slice column] as per the indexing in notes

# Total sales per year

print("This is the sum of sales of all restaurants yearly : \n",np.sum(sales_data,axis=0))
print("\n This is the sum of sales of each resturant in all four years : \n", np.sum(sales_data[:,1:],axis=1))
# we can slice data here also as per our need
print("\n Sales of pizza hub in all 4 years : \n",np.sum(sales_data[2,1:],axis = 0))
# If you are  jumping over columns to add values then axis = 0 and if jumping over rows then axis = 1
# If there is no data about axis provided only slicing done correctly automatically execute axis according to suitable slicing

# Maximum sales for each restaurant
max_sales =  np.max(sales_data[:,1:])
print(max_sales)
#if we don't put axis in this it will give us the max of whole sliced data
#axis = 0 tells that you have to give maximum of data column wise
max_sales =  np.max(sales_data[:,1:],axis = 0)
print(max_sales,"\n\n")

# Average sales per restaurant (here axis 1 as we want mean of data restaurant wise)
avg_sales = np.mean(sales_data[:,1:],axis = 1)
#but mean returns the value in 1d vector with dot that tells it is row wise
print(avg_sales)
#cummulative sales perform add and next function
cumsum = np.cumsum(sales_data[:,1:],axis = 1)
print("\n",cumsum)

# Gives size of plot not exact data that what it pixel or cm it can be any suitable unit
plt.figure(figsize=(10,6))
plt.plot(np.mean(cumsum,axis=0))
plt.title("Average cumulative sales across all restaurants")
plt.xlabel("Years")
plt.ylabel("Sales")
plt.grid(True)
plt.show()

